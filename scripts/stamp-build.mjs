// Stamps the commit this build came from into server/build.generated.js, so
// /api/health can answer the one question nobody could answer: is production
// running the code we think it is?
//
// Six commits once sat pushed and unshipped for a day because a push to main
// does not deploy this project and nothing anywhere said so. A deployment that
// cannot name its own commit is a deployment you have to take on trust.
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// Vercel sets this for a git-triggered build. A CLI deploy builds from
// uploaded source with no .git, so git is the fallback, not the first choice.
const fromEnv = process.env.VERCEL_GIT_COMMIT_SHA || '';
let commit = fromEnv.slice(0, 12);
if (!commit) {
  try { commit = execSync('git rev-parse --short=12 HEAD', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); }
  catch { commit = ''; }
}
// A build with uncommitted changes is not any commit, and saying it is would
// be worse than saying nothing.
let dirty = false;
try { dirty = execSync('git status --porcelain', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim().length > 0; }
catch { /* no git here, which is normal in a CLI deploy's build container */ }

const build = { commit: commit || 'unknown', dirty: dirty || undefined, built_at: new Date().toISOString() };
fs.writeFileSync(
  path.join(root, 'server', 'build.generated.js'),
  `// Generated by scripts/stamp-build.mjs — do not edit.\nexport const BUILD = ${JSON.stringify(build)};\n`
);
console.log(`[build] ${build.commit}${dirty ? ' (dirty tree)' : ''} at ${build.built_at}`);
