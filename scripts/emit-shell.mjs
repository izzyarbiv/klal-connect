// Captures the built index.html as a module the API can import.
//
// The serverless function needs the real shell — the hashed script and style
// tags Vite emits — to serve a crawlable page that still hydrates into the
// app. Reading dist/ at request time is not reliable inside a bundled
// function, so the shell is baked into a module at build time instead.
//
// Runs from `npm run build`, straight after `vite build`.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const shellPath = path.join(root, 'dist', 'index.html');
const outPath = path.join(root, 'server', 'shell.generated.js');

if (!fs.existsSync(shellPath)) {
  console.error('[shell] dist/index.html is missing — run vite build first.');
  process.exit(1);
}

const html = fs.readFileSync(shellPath, 'utf8');
fs.writeFileSync(outPath, `// Generated by scripts/emit-shell.mjs — do not edit.\nexport const SHELL = ${JSON.stringify(html)};\n`);
console.log(`[shell] wrote server/shell.generated.js (${(html.length / 1024).toFixed(1)}KB)`);
